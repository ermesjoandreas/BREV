//! Brev core: the mail layer (package brev-mail, library `brev_core`).
//!
//! Identity, contacts, threads and letters, the message crypto and the
//! relay client, on top of brev-vault, which holds the encrypted store, the
//! DEK and its `Locked`/`Unlocked` state, the column crypto, the padding and
//! the zeroing global allocator. The UniFFI surface is [`ping`], [`limits`],
//! [`Brev`] and [`OpenText`] (`ffi.rs`); the relay client is in `relay.rs`
//! (docs/PHASE3_DESIGN.md §5). Phase 4 (docs/PHASE4_DESIGN.md §5) adds
//! contact approval, invites and *Blokker*.
//!
//! `unsafe_code = "forbid"` is set at the workspace level. The UniFFI
//! scaffolding generated by `setup_scaffolding!` is the only code in this
//! crate that crosses the FFI boundary, and it is generated, not written.

